create or replace function public._is_bot_ua(p_ua text)
returns boolean
language sql
immutable
as $$
  select p_ua is null
      or btrim(p_ua) = ''
      or lower(p_ua) ~ '(bot|crawler|spider|preview|facebookexternalhit|facebot|whatsapp|telegram|slackbot|discordbot|linkedinbot|twitterbot|googlebot|bingbot|curl|wget|python-requests|go-http-client|headlesschrome|phantomjs|lighthouse|pingdom|uptime|monitor|http-client)';
$$;

revoke all on function public._is_bot_ua(text) from public, anon, authenticated;

