create or replace function public.get_timeseries(
  p_qr_id uuid default null,
  p_days integer default 30
)
returns table (
  day date,
  scans bigint,
  bot_scans bigint,
  unique_visitors bigint
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public._require_admin();

  return query
  with params as (
    select
      greatest(1, least(coalesce(p_days, 30), 365))::integer as v_days,
      (now() at time zone 'Africa/Cairo')::date as v_today
  ),
  days as (
    select generate_series(
      (select v_today - (v_days - 1) from params),
      (select v_today from params),
      interval '1 day'
    )::date as day
  )
  select
    d.day,
    count(s.id) filter (where not s.is_bot)::bigint as scans,
    count(s.id) filter (where s.is_bot)::bigint as bot_scans,
    count(distinct s.visitor_id) filter (where not s.is_bot)::bigint as unique_visitors
  from days d
  left join public.scans s
    on (s.created_at at time zone 'Africa/Cairo')::date = d.day
   and (p_qr_id is null or s.qr_id = p_qr_id)
  group by d.day
  order by d.day;
end;
$$;

create or replace function public.get_hourly_heatmap(p_qr_id uuid default null)
returns table (
  weekday integer,
  hour integer,
  scans bigint
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public._require_admin();

  return query
  with grid as (
    select w.weekday, h.hour
    from generate_series(0, 6) as w(weekday)
    cross join generate_series(0, 23) as h(hour)
  )
  select
    g.weekday,
    g.hour,
    count(s.id)::bigint as scans
  from grid g
  left join public.scans s
    on extract(dow from (s.created_at at time zone 'Africa/Cairo'))::integer = g.weekday
   and extract(hour from (s.created_at at time zone 'Africa/Cairo'))::integer = g.hour
   and not s.is_bot
   and (p_qr_id is null or s.qr_id = p_qr_id)
  group by g.weekday, g.hour
  order by g.weekday, g.hour;
end;
$$;

create or replace function public.get_funnel(p_qr_id uuid default null)
returns table (
  stage text,
  stage_order integer,
  count bigint,
  conversion_pct numeric
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public._require_admin();

  return query
  with scope_scans as (
    select count(distinct s.visitor_id)::numeric as scan_count
    from public.scans s
    where not s.is_bot
      and (p_qr_id is null or s.qr_id = p_qr_id)
  ),
  stages(stage, stage_order) as (
    values
      ('scan', 0),
      ('reveal_started', 1),
      ('reveal_completed', 2),
      ('tips_viewed', 3),
      ('waqi_cta_clicked', 4),
      ('quiz_completed', 5),
      ('share_clicked', 6),
      ('lang_toggled', 7),
      ('skipped_animation', 8)
  ),
  counts as (
    select
      v.stage,
      v.stage_order,
      case
        when v.stage = 'scan' then (select scan_count from scope_scans)
        else (
          select count(distinct e.visitor_id)::numeric
          from public.events e
          where e.event = v.stage
            and (p_qr_id is null or e.qr_id = p_qr_id)
            and exists (
              select 1
              from public.scans s
              where s.qr_id = e.qr_id
                and s.visitor_id = e.visitor_id
                and not s.is_bot
            )
        )
      end as cnt
    from stages v
  )
  select
    c.stage,
    c.stage_order,
    c.cnt::bigint as count,
    round(100.0 * c.cnt / nullif((select scan_count from scope_scans), 0), 1) as conversion_pct
  from counts c
  order by c.stage_order;
end;
$$;

create or replace function public.get_variant_comparison()
returns table (
  variant text,
  qr_count bigint,
  scans bigint,
  unique_visitors bigint,
  reveal_completed bigint,
  reveal_completed_rate numeric,
  cta_clicks bigint,
  cta_click_rate numeric
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public._require_admin();

  return query
  with qr_scans as (
    select
      q.id,
      coalesce(nullif(btrim(q.variant), ''), '(untagged)') as variant,
      count(s.id) filter (where not s.is_bot)::bigint as scans,
      count(distinct s.visitor_id) filter (where not s.is_bot)::bigint as visitors
    from public.qr_codes q
    left join public.scans s on s.qr_id = q.id
    group by q.id, q.variant
  ),
  qr_events as (
    select
      q.id,
      count(distinct e.visitor_id) filter (where e.event = 'reveal_completed')::bigint as reveal_completed,
      count(distinct e.visitor_id) filter (where e.event = 'waqi_cta_clicked')::bigint as cta_clicks
    from public.qr_codes q
    left join public.events e on e.qr_id = q.id
    where e.id is null or exists (
      select 1
      from public.scans s
      where s.qr_id = e.qr_id
        and s.visitor_id = e.visitor_id
        and not s.is_bot
    )
    group by q.id
  ),
  per_qr as (
    select
      qs.variant,
      qs.scans,
      qs.visitors,
      coalesce(qe.reveal_completed, 0) as reveal_completed,
      coalesce(qe.cta_clicks, 0) as cta_clicks
    from qr_scans qs
    left join qr_events qe on qe.id = qs.id
  )
  select
    p.variant,
    count(*)::bigint as qr_count,
    sum(p.scans)::bigint as scans,
    sum(p.visitors)::bigint as unique_visitors,
    sum(p.reveal_completed)::bigint as reveal_completed,
    round(100.0 * sum(p.reveal_completed) / nullif(sum(p.visitors), 0), 1) as reveal_completed_rate,
    sum(p.cta_clicks)::bigint as cta_clicks,
    round(100.0 * sum(p.cta_clicks) / nullif(sum(p.visitors), 0), 1) as cta_click_rate
  from per_qr p
  group by p.variant
  order by p.variant;
end;
$$;

create or replace function public.create_qr(
  p_label text,
  p_placement text default null,
  p_target_url text default null,
  p_slug text default null,
  p_variant text default null
)
returns public.qr_codes
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_slug text;
  v_row public.qr_codes;
  v_attempt integer;
begin
  perform public._require_admin();

  if p_label is null or btrim(p_label) = '' then
    raise exception 'label is required' using errcode = '22023';
  end if;

  if length(btrim(p_label)) > 120 then
    raise exception 'label is too long' using errcode = '22023';
  end if;

  if p_target_url is not null and p_target_url !~* '^https?://' then
    raise exception 'target_url must start with http:// or https://' using errcode = '22023';
  end if;

  if p_variant is not null and length(btrim(p_variant)) > 40 then
    raise exception 'variant is too long' using errcode = '22023';
  end if;

  if p_slug is not null and btrim(p_slug) <> '' then
    v_slug := lower(btrim(p_slug));
    if v_slug !~ '^[a-z0-9][a-z0-9-]{1,30}[a-z0-9]$' then
      raise exception 'slug must be 3-32 lowercase letters, numbers, or hyphens' using errcode = '22023';
    end if;

    insert into public.qr_codes (slug, label, placement, target_url, variant)
    values (v_slug, btrim(p_label), nullif(btrim(p_placement), ''), nullif(btrim(p_target_url), ''), nullif(btrim(p_variant), ''))
    returning * into v_row;

    return v_row;
  end if;

  for v_attempt in 1..10 loop
    v_slug := lower(substr(encode(gen_random_bytes(8), 'hex'), 1, 8));

    begin
      insert into public.qr_codes (slug, label, placement, target_url, variant)
      values (v_slug, btrim(p_label), nullif(btrim(p_placement), ''), nullif(btrim(p_target_url), ''), nullif(btrim(p_variant), ''))
      returning * into v_row;

      return v_row;
    exception when unique_violation then
      -- Extremely unlikely; generate another slug.
      null;
    end;
  end loop;

  raise exception 'could not generate a unique slug' using errcode = '23505';
end;
$$;

create or replace function public.export_scans_csv(p_qr_id uuid default null)
