-- WAQI QR awareness campaign - complete backend
-- Run this whole file in the Supabase SQL editor. It is safe to run again.
--
-- Privacy contract:
--   * No IP address, fingerprint, geolocation, or revealed device data is stored.
--   * The public can only call record_scan(), record_event(), and ping().
--   * All reads of campaign data require a signed-in admin.

begin;

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.qr_codes (
  id          uuid primary key default gen_random_uuid(),
  slug        text not null unique,
  label       text not null,
  placement   text,
  variant     text,
  target_url  text,
  active      boolean not null default true,
  starts_at   timestamptz,
  expires_at  timestamptz,
  created_at  timestamptz not null default now(),
  constraint qr_codes_slug_format check (slug ~ '^[a-z0-9][a-z0-9-]{1,30}[a-z0-9]$'),
  constraint qr_codes_target_url_http check (
    target_url is null or target_url ~* '^https?://'
  ),
  constraint qr_codes_dates check (
    starts_at is null or expires_at is null or starts_at < expires_at
  )
);

create table if not exists public.scans (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  qr_id       uuid not null references public.qr_codes(id) on delete cascade,
  visitor_id  text not null,
  user_agent  text,
  referrer    text,
  is_bot      boolean not null default false
);

create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  qr_id       uuid not null references public.qr_codes(id) on delete cascade,
  visitor_id  text not null,
  event       text not null,
  constraint events_event_check check (event in (
    'reveal_started',
    'reveal_completed',
    'tips_viewed',
    'waqi_cta_clicked',
    'share_clicked',
    'quiz_completed',
    'lang_toggled',
    'skipped_animation'
  )),
  constraint events_one_per_visitor unique (qr_id, visitor_id, event)
);

-- Keep the CHECK constraint current when this file is re-run after an edit.
alter table public.events drop constraint if exists events_event_check;
alter table public.events add constraint events_event_check check (event in (
  'reveal_started',
  'reveal_completed',
  'tips_viewed',
  'waqi_cta_clicked',
  'share_clicked',
  'quiz_completed',
  'lang_toggled',
  'skipped_animation'
));

create index if not exists scans_qr_created_idx
  on public.scans (qr_id, created_at desc);
create index if not exists scans_created_idx
  on public.scans (created_at desc);
create index if not exists scans_visitor_recent_idx
  on public.scans (qr_id, visitor_id, created_at desc);
create index if not exists events_qr_created_idx
  on public.events (qr_id, created_at desc);
create index if not exists events_created_idx
  on public.events (created_at desc);

-- ---------------------------------------------------------------------------
-- Row Level Security. Default deny. anon has no table privileges at all.
-- ---------------------------------------------------------------------------

alter table public.qr_codes enable row level security;
alter table public.scans    enable row level security;
alter table public.events   enable row level security;

revoke all on table public.qr_codes, public.scans, public.events from anon;
revoke all on table public.qr_codes, public.scans, public.events from authenticated;

grant select, insert, update, delete on table public.qr_codes to authenticated;
grant select on table public.scans  to authenticated;
