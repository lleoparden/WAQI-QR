create or replace function public.get_overview()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_result jsonb;
begin
  perform public._require_admin();

  select jsonb_build_object(
    'total_scans', (select count(*) from public.scans),
    'unique_visitors', (select count(distinct visitor_id) from public.scans),
    'human_scans', (select count(*) from public.scans where not is_bot),
    'human_unique_visitors', (select count(distinct visitor_id) from public.scans where not is_bot),
    'bot_scans', (select count(*) from public.scans where is_bot),
    'active_qr_count', (
      select count(*) from public.qr_codes q
      where q.active
        and (q.starts_at is null or q.starts_at <= now())
        and (q.expires_at is null or q.expires_at > now())
    ),
    'scans_24h', (
      select count(*) from public.scans
      where not is_bot and created_at > now() - interval '24 hours'
    ),
    'bot_scans_24h', (
      select count(*) from public.scans
      where is_bot and created_at > now() - interval '24 hours'
    )
  ) into v_result;

  return v_result;
end;
$$;

