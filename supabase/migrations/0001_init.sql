create or replace view public.v_qr_stats as
select
  q.id,
  q.slug,
  q.label,
  q.placement,
  q.variant,
  q.target_url,
  q.active,
  q.starts_at,
  q.expires_at,
  q.created_at,
  (select count(*) from public.scans s where s.qr_id = q.id)::bigint as total_scans,
  (select count(*) from public.scans s where s.qr_id = q.id and not s.is_bot)::bigint as human_scans,
  (select count(*) from public.scans s where s.qr_id = q.id and s.is_bot)::bigint as bot_scans,
  (select count(distinct s.visitor_id) from public.scans s where s.qr_id = q.id)::bigint as unique_visitors,
  (select count(distinct s.visitor_id) from public.scans s where s.qr_id = q.id and not s.is_bot)::bigint as unique_human_visitors,
  (select max(s.created_at) from public.scans s where s.qr_id = q.id) as last_scan_at,
  (select count(*) from public.scans s
    where s.qr_id = q.id and not s.is_bot
      and s.created_at > now() - interval '24 hours')::bigint as scans_24h
from public.qr_codes q;

revoke all on table public.v_qr_stats from public, anon, authenticated;

