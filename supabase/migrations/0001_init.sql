create or replace function public.record_scan(
  p_slug text,
  p_visitor_id text,
  p_user_agent text default null,
  p_referrer text default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_qr_id uuid;
  v_slug  text := lower(btrim(coalesce(p_slug, '')));
  v_ua    text := left(coalesce(p_user_agent, ''), 512);
  v_ref   text := left(coalesce(p_referrer, ''), 1024);
begin
  if v_slug !~ '^[a-z0-9][a-z0-9-]{1,30}[a-z0-9]$' then
    return;
  end if;

  if p_visitor_id is null or p_visitor_id !~ '^[A-Za-z0-9_-]{8,128}$' then
    return;
  end if;

  v_qr_id := public._slug_is_live(v_slug);
  if v_qr_id is null then
    return;
  end if;

  -- Serialize a visitor's concurrent scans so the 10-second window is reliable.
  perform pg_advisory_xact_lock(hashtextextended(v_qr_id::text || ':' || p_visitor_id, 0));

  if exists (
    select 1
    from public.scans s
    where s.qr_id = v_qr_id
      and s.visitor_id = p_visitor_id
      and s.created_at > now() - interval '10 seconds'
  ) then
    return;
  end if;

  insert into public.scans (qr_id, visitor_id, user_agent, referrer, is_bot)
  values (v_qr_id, p_visitor_id, nullif(v_ua, ''), nullif(v_ref, ''), public._is_bot_ua(v_ua));
end;
$$;

create or replace function public.record_event(
  p_slug text,
  p_visitor_id text,
  p_event text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_qr_id uuid;
  v_slug  text := lower(btrim(coalesce(p_slug, '')));
begin
  if p_event is null or p_event not in (
    'reveal_started',
    'reveal_completed',
    'tips_viewed',
    'waqi_cta_clicked',
    'share_clicked',
    'quiz_completed',
    'lang_toggled',
    'skipped_animation'
  ) then
    return;
  end if;

  if v_slug !~ '^[a-z0-9][a-z0-9-]{1,30}[a-z0-9]$' then
    return;
  end if;

  if p_visitor_id is null or p_visitor_id !~ '^[A-Za-z0-9_-]{8,128}$' then
    return;
  end if;

  v_qr_id := public._slug_is_live(v_slug);
  if v_qr_id is null then
    return;
  end if;

  -- Only visitors who actually scanned this QR can add funnel events.
  if not exists (
    select 1
    from public.scans s
    where s.qr_id = v_qr_id
      and s.visitor_id = p_visitor_id
  ) then
    return;
  end if;

  insert into public.events (qr_id, visitor_id, event)
  values (v_qr_id, p_visitor_id, p_event)
  on conflict (qr_id, visitor_id, event) do nothing;
end;
$$;

