create or replace function public._slug_is_live(p_slug text)
returns uuid
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select q.id
  from public.qr_codes q
  where q.slug = lower(btrim(p_slug))
    and q.active
    and (q.starts_at is null or q.starts_at <= now())
    and (q.expires_at is null or q.expires_at > now())
  limit 1;
$$;

revoke all on function public._slug_is_live(text) from public, anon, authenticated;

